import { build } from "esbuild";
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";

const root = process.cwd();
const entryPoint = resolve(root, "client/src/plugin-ui/sportfolio-widget-entry.ts");
const outputPath = resolve(root, "server/mcp/plugin/ui/generated-widget.ts");
const defaultAssetOrigin = "https://www.sportfolio.market";

// Build one self-contained ESM module for the MCP iframe. Dynamic imports in the
// entrypoint are folded into this bundle when splitting is disabled, so the UI
// does not depend on a second network request after ChatGPT loads the resource.
const result = await build({
  entryPoints: [entryPoint],
  bundle: true,
  write: false,
  platform: "browser",
  format: "esm",
  splitting: false,
  target: ["es2020"],
  jsx: "automatic",
  minify: true,
  legalComments: "none",
  define: {
    "process.env.NODE_ENV": JSON.stringify("production"),
  },
});

const javascript = result.outputFiles.find((file) => file.path.endsWith(".js"));
if (!javascript) {
  throw new Error("The Sportfolio plugin UI build did not emit a JavaScript module.");
}

// Prevent user-controlled/source strings in the bundle from ever terminating
// the containing script tag when the module is embedded in the HTML resource.
const inlineModule = javascript.text.replace(/<\/script/gi, "<\\/script");
const html = `<!doctype html>
<html lang="en">
  <head>
    <meta charset="utf-8" />
    <meta name="viewport" content="width=device-width,initial-scale=1,viewport-fit=cover" />
    <meta name="color-scheme" content="light dark" />
    <title>Sportfolio</title>
  </head>
  <body>
    <div id="root"></div>
    <script type="module">${inlineModule}</script>
  </body>
</html>`;

mkdirSync(dirname(outputPath), { recursive: true });
writeFileSync(
  outputPath,
  `// Generated by scripts/build-plugin-ui.mjs. Do not edit directly.\n` +
    `export const SPORTFOLIO_WIDGET_HTML_TEMPLATE = ${JSON.stringify(html)};\n` +
    `export function buildSportfolioWidgetHtml(_assetOrigin = ${JSON.stringify(defaultAssetOrigin)}) {\n` +
    `  return SPORTFOLIO_WIDGET_HTML_TEMPLATE;\n` +
    `}\n` +
    `export const SPORTFOLIO_WIDGET_HTML = buildSportfolioWidgetHtml();\n`,
  "utf8",
);

console.log(
  `Built self-contained Sportfolio plugin UI (${Buffer.byteLength(html, "utf8")} HTML bytes; ${javascript.contents.byteLength} JS bytes).`,
);
