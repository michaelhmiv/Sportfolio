import { build } from "esbuild";
import { mkdirSync, rmSync, writeFileSync } from "node:fs";
import { dirname, relative, resolve } from "node:path";

const root = process.cwd();
const entryPoint = resolve(root, "client/src/plugin-ui/sportfolio-widget-entry.ts");
const publicRoot = resolve(root, "client/public");
// Keep the immutable plugin assets in client/public/assets/plugin-ui so Vite copies them into dist/public.
const assetOutputDir = resolve(publicRoot, "assets/plugin-ui");
const outputPath = resolve(root, "server/mcp/plugin/ui/generated-widget.ts");
const assetOriginPlaceholder = "__SPORTFOLIO_ASSET_ORIGIN__";
const defaultAssetOrigin = "https://www.sportfolio.market";

rmSync(assetOutputDir, { recursive: true, force: true });
mkdirSync(assetOutputDir, { recursive: true });

// ESM splitting keeps the loader tiny and defers each card surface until its view is actually rendered.
const result = await build({
  entryPoints: { "sportfolio-widget": entryPoint },
  outdir: assetOutputDir,
  bundle: true,
  write: true,
  platform: "browser",
  format: "esm",
  splitting: true,
  target: ["es2020"],
  jsx: "automatic",
  minify: true,
  legalComments: "none",
  entryNames: "[name]-[hash]",
  chunkNames: "chunks/[name]-[hash]",
  assetNames: "assets/[name]-[hash]",
  metafile: true,
  define: {
    "process.env.NODE_ENV": JSON.stringify("production"),
  },
});

function publicUrlForOutput(outputKey) {
  const absolutePath = resolve(root, outputKey);
  const publicPath = relative(publicRoot, absolutePath).replaceAll("\\", "/");
  return `/${publicPath}`;
}

const entryOutput = Object.entries(result.metafile.outputs).find(([, metadata]) => {
  if (!metadata.entryPoint) return false;
  return resolve(root, metadata.entryPoint) === entryPoint;
});

if (!entryOutput) {
  throw new Error("The Sportfolio plugin UI build did not emit an entry JavaScript module.");
}

const [entryOutputKey, entryMetadata] = entryOutput;
const scriptUrl = `${assetOriginPlaceholder}${publicUrlForOutput(entryOutputKey)}`;
const cssUrl = entryMetadata.cssBundle
  ? `${assetOriginPlaceholder}${publicUrlForOutput(entryMetadata.cssBundle)}`
  : null;

const html = `<!doctype html>
<html lang="en">
  <head>
    <meta charset="utf-8" />
    <meta name="viewport" content="width=device-width,initial-scale=1,viewport-fit=cover" />
    <meta name="color-scheme" content="light dark" />
    <title>Sportfolio</title>
    ${cssUrl ? `<link rel="stylesheet" href="${cssUrl}" />` : ""}
  </head>
  <body>
    <div id="root"></div>
    <script type="module" src="${scriptUrl}"></script>
  </body>
</html>`;

const assetFiles = Object.keys(result.metafile.outputs)
  .map((outputKey) => ({
    path: publicUrlForOutput(outputKey),
    bytes: result.metafile.outputs[outputKey]?.bytes || 0,
  }))
  .sort((left, right) => right.bytes - left.bytes);
const totalAssetBytes = assetFiles.reduce((sum, asset) => sum + asset.bytes, 0);

mkdirSync(dirname(outputPath), { recursive: true });
writeFileSync(
  outputPath,
  `// Generated by scripts/build-plugin-ui.mjs. Do not edit directly.\n` +
    `export const SPORTFOLIO_WIDGET_ASSET_ORIGIN_PLACEHOLDER = ${JSON.stringify(assetOriginPlaceholder)};\n` +
    `export const SPORTFOLIO_WIDGET_HTML_TEMPLATE = ${JSON.stringify(html)};\n` +
    `export function buildSportfolioWidgetHtml(assetOrigin = ${JSON.stringify(defaultAssetOrigin)}) {\n` +
    `  const normalizedOrigin = assetOrigin.replace(/\\/+$/, \"\");\n` +
    `  return SPORTFOLIO_WIDGET_HTML_TEMPLATE.replaceAll(SPORTFOLIO_WIDGET_ASSET_ORIGIN_PLACEHOLDER, normalizedOrigin);\n` +
    `}\n` +
    `export const SPORTFOLIO_WIDGET_HTML = buildSportfolioWidgetHtml();\n`,
  "utf8",
);

console.log(
  `Built Sportfolio plugin UI loader (${Buffer.byteLength(html, "utf8")} bytes) with ${assetFiles.length} immutable asset(s) (${totalAssetBytes} bytes total).`,
);
for (const asset of assetFiles.slice(0, 8)) {
  console.log(`  ${asset.path}: ${asset.bytes} bytes`);
}
