import { build } from "esbuild";
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";

const root = process.cwd();
const entryPoint = resolve(root, "client/src/plugin-ui/sportfolio-widget.tsx");
const outputPath = resolve(root, "server/mcp/plugin/ui/generated-widget.ts");

const result = await build({
  entryPoints: [entryPoint],
  outfile: "sportfolio-widget.js",
  bundle: true,
  write: false,
  platform: "browser",
  format: "iife",
  target: ["es2020"],
  jsx: "automatic",
  minify: true,
  legalComments: "none",
  define: {
    "process.env.NODE_ENV": JSON.stringify("production"),
  },
});

const javascript =
  result.outputFiles.find((file) => file.path.endsWith(".js"))?.text ||
  result.outputFiles[0]?.text;
const stylesheet = result.outputFiles.find((file) => file.path.endsWith(".css"))?.text || "";

if (!javascript) {
  throw new Error("The Sportfolio plugin UI build did not emit JavaScript.");
}

const safeJavascript = javascript.replaceAll("</script", "<\\/script");
const safeStylesheet = stylesheet.replaceAll("</style", "<\\/style");
const html = `<!doctype html>
<html lang="en">
  <head>
    <meta charset="utf-8" />
    <meta name="viewport" content="width=device-width,initial-scale=1,viewport-fit=cover" />
    <meta name="color-scheme" content="light dark" />
    <title>Sportfolio</title>
    <style>${safeStylesheet}</style>
  </head>
  <body>
    <div id="root"></div>
    <script>${safeJavascript}</script>
  </body>
</html>`;

mkdirSync(dirname(outputPath), { recursive: true });
writeFileSync(
  outputPath,
  `// Generated by scripts/build-plugin-ui.mjs. Do not edit directly.\nexport const SPORTFOLIO_WIDGET_HTML = ${JSON.stringify(html)};\n`,
  "utf8",
);

console.log(`Built Sportfolio plugin UI (${Buffer.byteLength(html, "utf8")} bytes).`);
